/**
 * Кастомный класс ошибки с кодом и HTTP-статусом.
 * Используется в сервисах — бросается как `throw new AppError('NOT_FOUND', 404)`.
 */
export class AppError extends Error {
  code: string;
  status: number;
  details?: unknown;

  constructor(code: keyof typeof ERROR_CODES, status: number, details?: unknown) {
    super(ERROR_MESSAGES[ERROR_CODES[code]] ?? 'Ошибка');
    this.code = ERROR_CODES[code];
    this.status = status;
    this.details = details;
    this.name = 'AppError';
  }
}