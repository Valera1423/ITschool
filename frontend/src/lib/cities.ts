/**
 * Получить координаты города с fallback.
 */
export function getCityCoord(city: string): CityCoord & { fallback: boolean } {
  if (!city) return { ...CITY_COORDS['Москва'], fallback: true };

  // Точное совпадение
  const exact = CITY_COORDS[city];
  if (exact) return { ...exact, fallback: false };

  // По частичному совпадению
  const lower = city.toLowerCase().trim();
  for (const [name, coord] of Object.entries(CITY_COORDS)) {
    if (name.toLowerCase().includes(lower) || lower.includes(name.toLowerCase())) {
      return { ...coord, fallback: false };
    }
  }

  return { ...CITY_COORDS['Москва'], fallback: true };
}

